import { bahtText } from './bahttext.ts';

let fail = 0;
const cases: [number, string][] = [
  [0, 'ศูนย์บาทถ้วน'],
  [1, 'หนึ่งบาทถ้วน'],
  [10, 'สิบบาทถ้วน'],
  [11, 'สิบเอ็ดบาทถ้วน'],
  [21, 'ยี่สิบเอ็ดบาทถ้วน'],
  [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
  [120, 'หนึ่งร้อยยี่สิบบาทถ้วน'],
  [1001, 'หนึ่งพันเอ็ดบาทถ้วน'],
  [1250.5, 'หนึ่งพันสองร้อยห้าสิบบาทห้าสิบสตางค์'],
  [0.25, 'ยี่สิบห้าสตางค์'],
  [0.01, 'หนึ่งสตางค์'],
  [0.11, 'สิบเอ็ดสตางค์'],
  [1000000, 'หนึ่งล้านบาทถ้วน'],
  [1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
  [11000000, 'สิบเอ็ดล้านบาทถ้วน'],
  [21500000, 'ยี่สิบเอ็ดล้านห้าแสนบาทถ้วน'],
  [1000000000000, 'หนึ่งล้านล้านบาทถ้วน'],
  [35.99, 'สามสิบห้าบาทเก้าสิบเก้าสตางค์'],
  [100.1, 'หนึ่งร้อยบาทสิบสตางค์'],
];
for (const [n, want] of cases) {
  const got = bahtText(n);
  const ok = got === want;
  if (!ok) fail++;
  console.log(`${ok ? 'PASS' : 'FAIL'} ${n}${ok ? '' : `\n  got  ${got}\n  want ${want}`}`);
}
process.exit(fail ? 1 : 0);
